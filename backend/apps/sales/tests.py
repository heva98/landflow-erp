@pytest.mark.django_db
def test_direct_cash_sale_marks_plot_sold_and_generates_documents(api_client, agent, plot, customer):
    plot.status = Plot.Status.AVAILABLE
    plot.save(update_fields=['status'])
    api_client.force_authenticate(user=agent)

    response = api_client.post(reverse('sale-list'), {
        'plot': str(plot.id), 'customer': str(customer.id), 'sale_type': Sale.SaleType.CASH,
        'sale_price': '20000000.00', 'down_payment': '20000000.00', 'payment_method': 'cash',
    })

    assert response.status_code == status.HTTP_201_CREATED, response.data
    plot.refresh_from_db()
    assert plot.status == Plot.Status.SOLD
    assert plot.owner_id == customer.id

    sale = Sale.objects.get(pk=response.data['id'])
    assert sale.sold_by_id == agent.id
    assert hasattr(sale, 'invoice')
    assert sale.invoice.amount == sale.net_price
    assert sale.invoice.file.name
    assert sale.receipts.count() == 1
    receipt = sale.receipts.first()
    assert receipt.amount == sale.down_payment
    assert receipt.file.name


