@pytest.mark.django_db
def test_sale_from_reservation_marks_reservation_converted(api_client, agent, plot, customer):
    plot.status = Plot.Status.RESERVED
    plot.save(update_fields=['status'])
    reservation = Reservation.objects.create(
        plot=plot, customer=customer, reservation_fee=Decimal('100000.00'),
        expiry_date=timezone.now() + timedelta(days=7),
    )
    api_client.force_authenticate(user=agent)

    response = api_client.post(reverse('sale-list'), {
        'reservation': str(reservation.id), 'sale_type': Sale.SaleType.CASH,
        'sale_price': '20000000.00', 'down_payment': '20000000.00', 'payment_method': 'bank_transfer',
    })

    assert response.status_code == status.HTTP_201_CREATED, response.data
    reservation.refresh_from_db()
    plot.refresh_from_db()
    assert reservation.status == Reservation.Status.CONVERTED
    assert reservation.converted_at is not None
    assert plot.status == Plot.Status.SOLD
    assert plot.owner_id == customer.id


