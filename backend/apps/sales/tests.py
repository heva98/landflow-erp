@pytest.mark.django_db
def test_cancel_reverts_plot_to_available(api_client, agent, plot, customer):
    plot.status = Plot.Status.SOLD
    plot.owner = customer
    plot.save(update_fields=['status', 'owner'])
    sale = Sale.objects.create(
        plot=plot, customer=customer, sale_type=Sale.SaleType.CASH,
        sale_price=Decimal('20000000.00'), down_payment=Decimal('20000000.00'),
    )
    api_client.force_authenticate(user=agent)

    response = api_client.post(reverse('sale-cancel', args=[sale.id]))
    assert response.status_code == status.HTTP_200_OK
    sale.refresh_from_db()
    plot.refresh_from_db()
    assert sale.status == Sale.Status.CANCELLED
    assert sale.cancelled_at is not None
    assert plot.status == Plot.Status.AVAILABLE
    assert plot.owner_id is None


