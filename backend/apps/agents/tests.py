@pytest.mark.django_db
def test_sale_by_agent_auto_creates_commission_payment(api_client, sales_agent_user, agent, plot, customer):
    plot.status = Plot.Status.AVAILABLE
    plot.save(update_fields=['status'])
    api_client.force_authenticate(user=sales_agent_user)

    response = api_client.post(reverse('sale-list'), {
        'plot': str(plot.id), 'customer': str(customer.id), 'sale_type': Sale.SaleType.CASH,
        'sale_price': '20000000.00', 'down_payment': '20000000.00', 'payment_method': 'cash',
    })
    assert response.status_code == status.HTTP_201_CREATED, response.data

    sale = Sale.objects.get(id=response.data['id'])
    payment = CommissionPayment.objects.get(sale=sale)
    assert payment.agent_id == agent.id
    assert payment.amount == Decimal('600000.00')
    assert payment.status == CommissionPayment.Status.PENDING


@pytest.mark.django_db
def test_sale_by_non_agent_user_does_not_create_commission_payment(api_client, managing_director, plot, customer):
    plot.status = Plot.Status.AVAILABLE
