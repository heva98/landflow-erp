@pytest.mark.django_db
def test_rankings_orders_agents_by_approved_and_paid_commission(api_client, managing_director, agent):
    CommissionPayment.objects.create(agent=agent, amount=Decimal('600000.00'), status=CommissionPayment.Status.APPROVED)
