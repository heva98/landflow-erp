@pytest.mark.django_db
def test_managing_director_commission_payment_approve_paid_workflow(api_client, managing_director, agent):
    payment = CommissionPayment.objects.create(agent=agent, amount=Decimal('600000.00'))
    api_client.force_authenticate(user=managing_director)

    response = api_client.post(reverse('commissionpayment-mark-paid', args=[payment.id]))
    assert response.status_code == status.HTTP_400_BAD_REQUEST

    response = api_client.post(reverse('commissionpayment-approve', args=[payment.id]))
    assert response.status_code == status.HTTP_200_OK
    payment.refresh_from_db()
    assert payment.status == CommissionPayment.Status.APPROVED
    assert payment.approved_by_id == managing_director.id

    response = api_client.post(
        reverse('commissionpayment-mark-paid', args=[payment.id]), {'payment_reference': 'TXN-001'},
    )
    assert response.status_code == status.HTTP_200_OK
    payment.refresh_from_db()
    assert payment.status == CommissionPayment.Status.PAID
    assert payment.payment_reference == 'TXN-001'


