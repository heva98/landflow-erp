    api_client.force_authenticate(user=managing_director)

    response = api_client.get(reverse('agent-rankings'))
    assert response.status_code == status.HTTP_200_OK
    assert response.data[0]['id'] == str(agent.id)
    assert Decimal(response.data[0]['total_commission']) == Decimal('600000.00')
    assert response.data[0]['sale_count'] == 1
    assert response.data[0]['rank'] == 1
