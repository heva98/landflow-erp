@pytest.mark.django_db
def test_finance_manager_process_and_mark_paid_workflow(api_client, finance_manager, payroll_record):
    api_client.force_authenticate(user=finance_manager)

    response = api_client.post(reverse('payrollrecord-mark-paid', args=[payroll_record.id]))
    assert response.status_code == status.HTTP_400_BAD_REQUEST

    response = api_client.post(reverse('payrollrecord-process', args=[payroll_record.id]))
    assert response.status_code == status.HTTP_200_OK
    payroll_record.refresh_from_db()
    assert payroll_record.status == PayrollRecord.Status.PROCESSED
    assert payroll_record.processed_at is not None

    response = api_client.post(reverse('payrollrecord-mark-paid', args=[payroll_record.id]))
    assert response.status_code == status.HTTP_200_OK
    payroll_record.refresh_from_db()
    assert payroll_record.status == PayrollRecord.Status.PAID
    assert payroll_record.paid_at is not None
