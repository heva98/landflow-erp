@pytest.mark.django_db
def test_employee_lifecycle_actions(api_client, managing_director, employee):
    api_client.force_authenticate(user=managing_director)

    response = api_client.post(reverse('employee-put-on-leave', args=[employee.id]))
    assert response.status_code == status.HTTP_200_OK
    employee.refresh_from_db()
    assert employee.status == Employee.Status.ON_LEAVE

    response = api_client.post(reverse('employee-activate', args=[employee.id]))
    assert response.status_code == status.HTTP_200_OK
    employee.refresh_from_db()
    assert employee.status == Employee.Status.ACTIVE

    response = api_client.post(reverse('employee-suspend', args=[employee.id]))
    assert response.status_code == status.HTTP_200_OK
    employee.refresh_from_db()
    assert employee.status == Employee.Status.SUSPENDED

    response = api_client.post(reverse('employee-terminate', args=[employee.id]))
    assert response.status_code == status.HTTP_200_OK
    employee.refresh_from_db()
    assert employee.status == Employee.Status.TERMINATED
    assert employee.termination_date is not None

    response = api_client.post(reverse('employee-suspend', args=[employee.id]))
    assert response.status_code == status.HTTP_400_BAD_REQUEST


